"""Generate bundled RU/KK narration. Only original lesson text is sent to TTS."""
import asyncio, json, pathlib, edge_tts, hashlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
VOICES = {'ru': 'ru-RU-SvetlanaNeural', 'kk': 'kk-KZ-AigulNeural'}
async def main():
    lessons = json.loads((ROOT / 'generated/lessons.json').read_text(encoding='utf-8'))
    folder = ROOT / 'assets/audio'
    folder.mkdir(parents=True, exist_ok=True)
    semaphore = asyncio.Semaphore(2)
    failures = []
    async def generate(lesson, lang):
        text = lesson['title'][lang] + '. ' + ' '.join(c['text'][lang] for c in lesson['cards'])
        filename = folder / f"{lesson['id']}-{lang}.mp3"
        stamp = filename.with_suffix('.sha256')
        digest = hashlib.sha256(text.encode()).hexdigest()
        if filename.exists() and filename.stat().st_size > 1000 and stamp.exists() and stamp.read_text() == digest:
            return
        async with semaphore:
            for attempt in range(6):
                try:
                    voice = ('en-US-AvaMultilingualNeural' if attempt > 1 else 'ru-RU-DmitryNeural') if lang == 'ru' and attempt > 0 else VOICES[lang]
                    await asyncio.wait_for(edge_tts.Communicate(text, voice, rate='+0%' if attempt > 2 else '-10%').save(str(filename)), timeout=20)
                    stamp.write_text(digest)
                    filename.with_suffix('.voice').write_text(voice)
                    print(f"OK {lesson['id']} {lang}", flush=True)
                    return
                except Exception as exc:
                    if attempt == 5: failures.append(f"{lesson['id']}/{lang}: {exc}")
                    else: await asyncio.sleep(2 * (attempt + 1))
    await asyncio.gather(*(generate(l,lang) for l in lessons for lang in VOICES))
    if failures: raise RuntimeError('\n'.join(failures))
    manifest = "// Generated by scripts/audio.py. All assets are bundled for offline playback.\nexport const audio: Record<string, number> = {\n"
    for l in lessons:
        for lang in VOICES:
            key = f"{l['id']}-{lang}"
            manifest += f"  '{key}': require('../assets/audio/{key}.mp3'),\n"
    manifest += '};\n'
    (ROOT / 'src/audio.ts').write_text(manifest, encoding='utf-8')
    print('Audio ready: ' + str(len(lessons)*2), flush=True)
asyncio.run(main())
