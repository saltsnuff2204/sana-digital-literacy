const {test,expect}=require('@playwright/test');
test('theme persists offline and reaches lessons, auth and Kazakh settings',async({page,context})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByTestId('start-learning').click();
 await page.getByRole('tab',{name:'Настройки',exact:true}).click();
 await page.getByTestId('theme-dark').click();
 await expect(page.getByTestId('theme-dark')).toHaveCSS('background-color','rgb(48, 42, 75)');
 await expect(page.getByText('Оформление',{exact:true})).toHaveCSS('color','rgb(241, 240, 250)');
 await page.screenshot({path:'docs/screenshots/settings-dark.png',fullPage:true});
 await page.getByRole('button',{name:/Войти или создать аккаунт/}).click();
 await expect(page.getByRole('textbox',{name:'Логин',exact:true})).toHaveCSS('background-color','rgb(32, 32, 47)');
 await page.getByRole('button',{name:'Закрыть',exact:true}).click();
 await page.evaluate(async()=>{await navigator.serviceWorker.ready;});
 await expect.poll(()=>page.evaluate(()=>!!navigator.serviceWorker.controller)).toBe(true);
 await context.setOffline(true);await page.reload();
 await page.getByRole('tab',{name:'Настройки',exact:true}).click();
 await expect(page.getByTestId('theme-dark')).toHaveCSS('background-color','rgb(48, 42, 75)');
 await page.getByRole('radio',{name:'Қазақша',exact:true}).click();
 await expect(page.getByText('Қараңғы',{exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('tab',{name:'Басты бет',exact:true}).click();
 await page.screenshot({path:'docs/screenshots/home-dark-phone.png',fullPage:true});
 await page.getByRole('button',{name:/Алғашқы сабақ/}).click();
 await expect(page.getByText('Компьютер неден тұрады',{exact:true})).toHaveCSS('color','rgb(241, 240, 250)');
 await page.screenshot({path:'docs/screenshots/lesson-dark-phone.png',fullPage:true});
 await page.getByRole('button',{name:'Сабақтарға оралу',exact:true}).click();
 await page.getByRole('tab',{name:'Баптаулар',exact:true}).click();
 await page.getByTestId('theme-light').click();
 await expect(page.getByText('Безендіру',{exact:true})).toHaveCSS('color','rgb(32, 36, 61)');
 expect(errors).toEqual([]);
});
